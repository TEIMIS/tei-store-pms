-- Undo the earlier version (software lists on equipment types, etc.).
alter table public.equipment_types drop column if exists software;
alter table public.equipment_types drop column if exists sales_sending;
alter table public.pm_records      drop column if exists software;
alter table public.pm_records      drop column if exists sales;
alter table public.stores          drop column if exists mall_interface;
alter table public.stores          drop column if exists tenant_id;

-- Stores: lease type, and the mall for percentage-lease stores.
alter table public.stores add column if not exists lease_type    text not null default 'Fixed';
alter table public.stores add column if not exists mall_operator text not null default '';
update public.stores set mall_operator = 'SM Malls' where mall_operator = 'SM Supermalls';
update public.stores set mall_operator = '' where lease_type <> 'Percentage' or mall_operator not in ('Ayala Malls','SM Malls','Robinsons Malls');
alter table public.stores drop constraint if exists stores_lease_type_check;
alter table public.stores add constraint stores_lease_type_check check (lease_type in ('Fixed','Percentage'));
alter table public.stores drop constraint if exists stores_mall_check;
alter table public.stores add constraint stores_mall_check check (mall_operator in ('','Ayala Malls','SM Malls','Robinsons Malls'));

-- Each mall's daily sales sending software, as equipment types.
insert into public.equipment_types (id, name, prefix, category, freq_months, checklist) values
('t-sw-uno', 'Project UNO', 'Project UNO', 'Mall Sales Software', 1,
 '["Project UNO installed and running on the POS","Store / tenant code configured correctly","Connection to Ayala Malls server OK","Daily sales sent successfully","No missing or failed sending days"]'::jsonb),
('t-sw-mosaic', 'SIA Mosaic', 'SIA Mosaic', 'Mall Sales Software', 1,
 '["SIA Mosaic installed and running on the POS","Store / tenant code configured correctly","Connection to SM server OK","Daily sales sent successfully","No missing or failed sending days"]'::jsonb),
('t-sw-sftp', 'SFTP Server', 'SFTP Server', 'Mall Sales Software', 1,
 '["SFTP host and login configured correctly","SFTP connection test OK","Daily sales file generated by the POS","Daily sales file uploaded successfully","No missing or failed sending days"]'::jsonb)
on conflict (id) do nothing;

-- Percentage-lease stores that already have a mall get its software item.
insert into public.equipment (store_id, type_id, name)
select s.id,
       case s.mall_operator when 'Ayala Malls' then 't-sw-uno' when 'SM Malls' then 't-sw-mosaic' else 't-sw-sftp' end,
       case s.mall_operator when 'Ayala Malls' then 'Project UNO' when 'SM Malls' then 'SIA Mosaic' else 'SFTP Server' end
  from public.stores s
 where s.lease_type = 'Percentage' and s.mall_operator <> ''
   and not exists (select 1 from public.equipment e
                    where e.store_id = s.id
                      and e.type_id = case s.mall_operator when 'Ayala Malls' then 't-sw-uno' when 'SM Malls' then 't-sw-mosaic' else 't-sw-sftp' end);
